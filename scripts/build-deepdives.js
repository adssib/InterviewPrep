// Turns every Markdown file in deep-dives/ into data/deepdives.js for the site.
// Files whose name starts with "_" (like _TEMPLATE.md) are skipped.
// Run locally with: npm run build
const fs = require('fs');
const path = require('path');
const { marked } = require('marked');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'deep-dives');
const OUT = path.join(ROOT, 'data', 'deepdives.js');

const TYPES = ['chain', 'scenario', 'compare', 'estimate', 'checklist'];

// Topic ids that exist in the quiz data, so "topic:" can link to a drill.
global.window = global;
window.TOPICS = [];
for (const f of fs.readdirSync(path.join(ROOT, 'data'))) {
  if (f.endsWith('.js') && f !== 'deepdives.js') require(path.join(ROOT, 'data', f));
}
const TOPIC_IDS = new Set(window.TOPICS.map((t) => t.id));

marked.setOptions({ gfm: true, breaks: false });

function slugify(s) {
  return s.toLowerCase().replace(/\.md$/, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

function parseFrontmatter(text, file, errors) {
  const m = text.match(/^---\s*\n([\s\S]*?)\n---\s*\n?/);
  if (!m) { errors.push(`${file}: missing the --- header block at the top`); return { meta: {}, body: text }; }
  const meta = {};
  for (const line of m[1].split('\n')) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    const i = line.indexOf(':');
    if (i === -1) { errors.push(`${file}: header line "${line.trim()}" needs a colon, like "title: My question"`); continue; }
    meta[line.slice(0, i).trim().toLowerCase()] = line.slice(i + 1).trim();
  }
  return { meta, body: text.slice(m[0].length) };
}

// Split on "## Heading" lines (not inside code fences).
function splitSections(body, level) {
  const marker = '#'.repeat(level) + ' ';
  const out = [];
  let cur = null, inFence = false;
  for (const line of body.split('\n')) {
    if (/^\s*```/.test(line)) inFence = !inFence;
    if (!inFence && line.startsWith(marker)) {
      cur = { heading: line.slice(marker.length).trim(), lines: [] };
      out.push(cur);
    } else if (cur) {
      cur.lines.push(line);
    } else if (line.trim()) {
      out.push(cur = { heading: '', lines: [line] });
    }
  }
  return out.map((s) => ({ heading: s.heading, text: s.lines.join('\n').trim() }));
}

function render(md) {
  // let checklist boxes be ticked on the page
  return marked.parse(md)
    .replace(/<table>/g, '<div class="table-wrap"><table>').replace(/<\/table>/g, '</table></div>')
    .replace(/<input disabled="" type="checkbox">/g, '<input type="checkbox">')
    .replace(/<input checked="" disabled="" type="checkbox">/g, '<input type="checkbox" checked>');
}

const errors = [];
const items = [];
const seen = new Set();

const files = fs.existsSync(SRC) ? fs.readdirSync(SRC).filter((f) => f.endsWith('.md') && !f.startsWith('_')).sort() : [];

for (const file of files) {
  const raw = fs.readFileSync(path.join(SRC, file), 'utf8').replace(/\r\n/g, '\n');
  const { meta, body } = parseFrontmatter(raw, file, errors);
  const sections = splitSections(body, 2);

  const item = {
    id: 'dd-' + slugify(file),
    file,
    title: meta.title || '',
    type: (meta.type || 'scenario').toLowerCase(),
    topic: (meta.topic || '').toLowerCase(),
    tags: (meta.tags || '').split(',').map((t) => t.trim()).filter(Boolean),
    question: '',
    short: '',
    followups: [],
    sections: []
  };

  if (!item.title) errors.push(`${file}: add a "title:" line in the header`);
  if (!TYPES.includes(item.type)) errors.push(`${file}: type "${item.type}" isn't one of: ${TYPES.join(', ')}`);
  if (item.topic && !TOPIC_IDS.has(item.topic)) errors.push(`${file}: topic "${item.topic}" doesn't match a quiz topic. Use one of: ${[...TOPIC_IDS].join(', ')}`);
  if (seen.has(item.id)) errors.push(`${file}: another file has the same name`);
  seen.add(item.id);

  for (const s of sections) {
    const key = s.heading.toLowerCase();
    if (!s.text) continue;
    if (key === 'question') item.question = render(s.text);
    else if (key === 'short answer') item.short = render(s.text);
    else if (key === 'follow-ups' || key === 'follow ups' || key === 'followups') {
      for (const f of splitSections(s.text, 3)) {
        if (!f.heading) continue;
        item.followups.push({ q: marked.parseInline(f.heading), a: render(f.text || '_No answer written yet._') });
      }
    } else {
      item.sections.push({ heading: s.heading || 'Notes', html: render(s.text) });
    }
  }

  if (!item.question) errors.push(`${file}: add a "## Question" section`);
  items.push(item);
}

if (errors.length) {
  console.error('Deep dive problems:\n- ' + errors.join('\n- '));
  process.exit(1);
}

fs.writeFileSync(OUT, '// Generated by scripts/build-deepdives.js from deep-dives/*.md. Edit the Markdown files, not this.\nwindow.DEEPDIVES = ' + JSON.stringify(items) + ';\n');
console.log(`Built ${items.length} deep dives into data/deepdives.js`);
